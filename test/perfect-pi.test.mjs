import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, existsSync, writeFileSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { test } from 'node:test';
import { runCommand } from '../packages/wardrobe/src/commands.mjs';
import { RpcSession } from '../fixtures/lib/pi-runner.mjs';
import { launchEnv, useHarness } from './support/harness.mjs';
import { reviewAgentFiles } from '../packages/wardrobe/src/agent-files.mjs';
const root=resolve('presets/perfect-pi');
const read=path=>JSON.parse(readFileSync(join(root,path)));
const manifest=read('manifest.json'), pkg=read('package.json'), preset=read('preset.json'), migration=read('migration.json');
const harness=useHarness('perfect-pi');
const walk=dir=>readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(join(dir,e.name)):[join(dir,e.name)]);
test('full Perfect Pi ships every declared capability and pinned skill companion',()=>{
 assert.doesNotThrow(()=>reviewAgentFiles({captured:{root},alias:'self'}),'agent files must pass the real native installation review');
 assert.equal(pkg.pi.skills.length,47);assert.equal(pkg.pi.extensions.length,10);
 assert.deepEqual(Object.values(preset.packages).slice(1).map(p=>p.source),manifest.packages.map(p=>p.source));
 assert.deepEqual(preset.resources.find(r=>r.package==='native-7'&&r.kind==='extensions')?.include,['dist/index.ts']);
 assert.equal(preset.packages['native-7'].source,'npm:@narumitw/pi-statusline@0.50.2');
 assert.equal(pkg.wardrobe.agent.settings.theme,'dark');
 assert.ok(!pkg.pi.extensions.some(path=>/ccstyle/.test(path)));
 assert.ok(!Object.values(preset.packages).some(p=>/pi-cc-extensions/.test(p.source)));
 assert.equal(preset.resources.some(r=>r.package==='native-0'),false,'upstream SoL entry must stay disabled in favor of the adapter');
 for(const entry of manifest.skills) for(const name of entry.requiredSkills??(Array.isArray(entry.selection)?entry.selection:[])) assert.ok(pkg.pi.skills.includes('skills/'+name+'/SKILL.md'),name);
 for(const [path,hash] of Object.entries(migration.checksums)) assert.equal(createHash('sha256').update(readFileSync(join(root,path))).digest('hex'),hash,path);
 for(const name of manifest.skillPolicy.excludeFromPi) assert.ok(!pkg.pi.skills.includes('skills/'+name+'/SKILL.md'));
 assert.equal(pkg.wardrobe.agent.settings.perfectPiCompaction,undefined);
 assert.equal(manifest.defaultSettings.perfectPiCompaction,undefined);
 assert.equal(manifest.solPi.reducerPolicy.provider,undefined);
 assert.equal(manifest.solPi.reducerPolicy.model,undefined);
 assert.equal(read('global/sol-pi.json').evidencePreservingReducerProvider,undefined);
 for (const role of ['planner','reviewer','scout','worker']) assert.doesNotMatch(readFileSync(join(root,'global/agents',role+'.md'),'utf8'),/^model:/m);
 assert.ok(!pkg.pi.extensions.some(path=>/compaction-model|subagent-policy/.test(path)));
 for (const path of [...pkg.pi.skills,...pkg.pi.extensions]) assert.doesNotMatch(readFileSync(join(root,path),'utf8'),/cpa\/gemini-3\.8-flash-high|\/subagent-model|managed `subagent-policy`/,path);
 assert.ok(!pkg.wardrobe.agent.files.some(f=>/(?:auth|models)\.json$/.test(f.target)));
 for(const file of pkg.wardrobe.agent.files) assert.ok(existsSync(join(root,file.source)),file.source);
});
const full=process.env.WARDROBE_FULL_INTEGRATION==='1';
if(full){
 test('full Perfect Pi installs real pinned dependencies and starts through Wardrobe', {timeout:1800000},async t=>{
  const h=harness(); const files={'package.json':JSON.stringify({name:'full-workspace',version:'1.0.0'})};
  for(const path of walk(root))files['presets/perfect-pi/'+path.slice(root.length+1)]=readFileSync(path);
  const repo=await h.gitRepo('perfect-pi-full',[{message:'full native preset',files}]);
  const env=launchEnv(h,{WARDROBE_REGISTRY:'https://registry.npmjs.org',NPM_CONFIG_REGISTRY:'https://registry.npmjs.org',NPM_CONFIG_CACHE:'/tmp/wardrobe-perfect-pi-npm-cache',PI_MANAGED_INSTALL_ROOT:h.runtime.installRoot});
  const request='install '+repo.sourceAt(repo.commits[0])+' --preset presets/perfect-pi/preset.json';
  const review=await runCommand(request,{env});assert.equal(review.ok,true,JSON.stringify(review.result));
  const install=await runCommand(request+' --confirm '+review.result.plan.digest,{env});
  assert.equal(install.ok,true,JSON.stringify(install.result));assert.equal(install.result.state,'available',JSON.stringify(install.result));
  const dir=install.result.staging.agentDir,revision=install.result.staging.revision;
  console.log('Full integration revision:',revision);
  const child=h.sandbox.runner.fork(process.execPath,[resolve('packages/wardrobe/bin/wardrobe.mjs'),'run',revision,'--agent-dir',h.agentPath('primary'),'--','--mode','rpc','--offline','--no-session'],{cwd:h.sandbox.project,env});
  const session=new RpcSession(child,h.sandbox.runner,{agentName:'perfect-pi',agentDir:dir,eventsLog:h.sandbox.extensionLog});
  t.after(()=>{if(child.exitCode===null)child.kill('SIGKILL');});
  const commands=await session.commandNames();
  for(const name of ['wardrobe','skill:route','skill:maintain','skill:update','skill:frontend-design','skill:vercel-react-best-practices','mcp-key','tools'])assert.ok(commands.includes(name),name+' '+session.stderr);
  assert.equal((await session.close()).code,0,session.stderr);
  const doctor=await runCommand('doctor '+revision,{env});assert.equal(doctor.result.revisions[0].state,'available',JSON.stringify(doctor.result));
  assert.ok(existsSync(join(dir,'agents/implementer.md')));
  assert.ok(existsSync(join(dir,'scripts/mcp-launch.mjs')));
  assert.equal(existsSync(join(dir,'models.json')),false);
  assert.deepEqual(JSON.parse(readFileSync(join(dir,'sol-pi.json'))),read('global/sol-pi.json'));
  console.log(JSON.stringify({commandCount:commands.length,skills:commands.filter(n=>n.startsWith('skill:')).length,stderr:session.stderr.slice(-3000)}));
 });
}
