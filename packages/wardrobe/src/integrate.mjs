// Explicit, reversible shell/PATH integration for Pi and Wardrobe.
//
// Generates a thin forwarding wrapper named `pi` that records the real Pi
// executable at enable time. The wrapper intercepts `--wardrobe` to start the
// selector, while passing all ordinary Pi arguments, flags, cwd, and signals
// directly to the real Pi binary without recursion.

import { chmodSync, existsSync, mkdirSync, readFileSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { join, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";
import { isWardrobeShim, piCliOf } from "./lock.mjs";

/** Marker comment recognizing wardrobe-generated wrapper scripts. */
export const INTEGRATION_MARKER = "WARDROBE_INTEGRATION_WRAPPER";

/** Safely single-quote a string for POSIX shell scripts. */
function shQuote(str) {
  if (str === null || str === undefined) return "''";
  return "'" + String(str).replace(/'/g, "'\\''") + "'";
}

/**
 * Enable shell/PATH integration by writing a `pi` forwarding wrapper.
 *
 * Refuses if a file already exists at the target path (never overwrites).
 * Records the resolved real Pi absolute path inside the wrapper to avoid
 * PATH resolution recursion at run time.
 */
export function integrateEnable({
  dir,
  realPi = null,
  agentDir = null,
  env = process.env,
  stdout = process.stdout,
  stderr = process.stderr,
}) {
  if (!dir || typeof dir !== "string" || !dir.trim()) {
    stderr.write("wardrobe integrate enable requires --dir <path>\n");
    return 2;
  }

  const targetDir = resolvePath(dir.trim());
  const wrapperPath = join(targetDir, "pi");

  if (existsSync(wrapperPath)) {
    stderr.write(`refusing to overwrite existing file at ${wrapperPath}\n`);
    return 1;
  }

  let resolvedRealPi = realPi ? resolvePath(String(realPi).trim()) : null;
  if (!resolvedRealPi || !existsSync(resolvedRealPi) || isWardrobeShim(resolvedRealPi)) {
    resolvedRealPi = piCliOf(env, { agentDir });
  }

  if (!resolvedRealPi || !existsSync(resolvedRealPi) || isWardrobeShim(resolvedRealPi)) {
    stderr.write(
      "cannot locate real Pi executable to record in wrapper\n" +
        "  set WARDROBE_PI_CLI or ensure pi is installed on PATH\n"
    );
    return 1;
  }

  try {
    resolvedRealPi = realpathSync(resolvedRealPi);
  } catch {}

  const wardrobeBin = resolvePath(fileURLToPath(new URL("../bin/wardrobe.mjs", import.meta.url)));
  const resolvedAgentDir = agentDir
    ? resolvePath(String(agentDir).trim())
    : (env?.WARDROBE_AGENT_DIR ? resolvePath(String(env.WARDROBE_AGENT_DIR).trim()) : null);

  mkdirSync(targetDir, { recursive: true });

  const content = [
    "#!/bin/sh",
    "# Generated by wardrobe integrate",
    `# Marker: ${INTEGRATION_MARKER}`,
    `REAL_PI=${shQuote(resolvedRealPi)}`,
    `WARDROBE_BIN=${shQuote(wardrobeBin)}`,
    `NODE_BIN=${shQuote(process.execPath)}`,
    `RECORDED_AGENT_DIR=${resolvedAgentDir ? shQuote(resolvedAgentDir) : "''"}`,
    "",
    'if [ "$1" = "--wardrobe" ]; then',
    "  shift",
    '  export WARDROBE_PI_CLI="$REAL_PI"',
    '  if [ -n "$RECORDED_AGENT_DIR" ]; then',
    '    export WARDROBE_AGENT_DIR="${WARDROBE_AGENT_DIR:-$RECORDED_AGENT_DIR}"',
    "  fi",
    '  if [ -x "$WARDROBE_BIN" ]; then',
    '    exec "$WARDROBE_BIN" "$@"',
    "  else",
    '    exec "$NODE_BIN" "$WARDROBE_BIN" "$@"',
    "  fi",
    "else",
    '  case "$REAL_PI" in',
    "    *.js|*.mjs)",
    '      exec "$NODE_BIN" "$REAL_PI" "$@"',
    "      ;;",
    "    *)",
    '      if [ -x "$REAL_PI" ]; then',
    '        exec "$REAL_PI" "$@"',
    "      else",
    '        exec "$NODE_BIN" "$REAL_PI" "$@"',
    "      fi",
    "      ;;",
    "  esac",
    "fi",
    "",
  ].join("\n");

  writeFileSync(wrapperPath, content, { mode: 0o755 });
  try {
    chmodSync(wrapperPath, 0o755);
  } catch {}

  if (agentDir) {
    try {
      const recordedDir = join(agentDir, "wardrobe");
      mkdirSync(recordedDir, { recursive: true });
      writeFileSync(join(recordedDir, "pi-cli"), `${resolvedRealPi}\n`);
    } catch {}
  }

  stdout.write(
    `wardrobe integration enabled at ${wrapperPath}\n` +
      `real Pi executable recorded: ${resolvedRealPi}\n` +
      `to activate shell/PATH integration, prepend ${targetDir} to PATH:\n` +
      `  export PATH="${targetDir}:$PATH"\n`
  );
  return 0;
}

/**
 * Disable shell/PATH integration by removing the wrapper.
 *
 * Refuses to remove any file that was not generated by wardrobe integrate.
 */
export function integrateDisable({
  dir,
  stdout = process.stdout,
  stderr = process.stderr,
}) {
  if (!dir || typeof dir !== "string" || !dir.trim()) {
    stderr.write("wardrobe integrate disable requires --dir <path>\n");
    return 2;
  }

  const targetDir = resolvePath(dir.trim());
  const wrapperPath = join(targetDir, "pi");

  if (!existsSync(wrapperPath)) {
    stderr.write(`no wrapper file found at ${wrapperPath}\n`);
    return 1;
  }

  try {
    const content = readFileSync(wrapperPath, "utf8");
    if (!content.includes(INTEGRATION_MARKER) && !content.includes("Generated by wardrobe integrate")) {
      stderr.write(`refusing to remove ${wrapperPath}: not a wardrobe integration wrapper\n`);
      return 1;
    }
    unlinkSync(wrapperPath);
  } catch (error) {
    stderr.write(`failed to remove ${wrapperPath}: ${error.message}\n`);
    return 1;
  }

  stdout.write(`wardrobe integration disabled: removed ${wrapperPath}\n`);
  return 0;
}
