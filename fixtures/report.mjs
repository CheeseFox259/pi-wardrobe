// Merge per-check evidence files into one report.
//
// Run after the suite: `npm run fixtures:report`.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_EVIDENCE_DIR, NOT_CLAIMED } from "./lib/evidence.mjs";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const evidenceDir = resolve(REPO_ROOT, process.argv[2] ?? DEFAULT_EVIDENCE_DIR);
const reportPath = join(evidenceDir, "native-fixture-report.md");

if (!existsSync(evidenceDir)) {
  console.error(`No evidence directory at ${evidenceDir}. Run npm test first.`);
  process.exit(1);
}

/**
 * Payload files whose label starts with this prefix are harness self-tests.
 * They deliberately record a failure, so the merged report must skip them.
 */
const SELF_TEST_PREFIX = "self-test-";

const payloads = readdirSync(evidenceDir)
  .filter((name) => name.endsWith(".json"))
  .sort()
  .map((name) => JSON.parse(readFileSync(join(evidenceDir, name), "utf8")))
  .filter((payload) => !payload.label.startsWith(SELF_TEST_PREFIX));

if (payloads.length === 0) {
  console.error(`No evidence JSON files in ${evidenceDir}. Run npm test first.`);
  process.exit(1);
}

const failures = payloads.reduce((total, payload) => total + payload.failures, 0);
const runtime = payloads[0].runtime;

const lines = [
  "# Wardrobe V1 native fixture report",
  "",
  "Generated by `npm run fixtures:verify`. Every check below ran a real Pi",
  "process against controlled loopback sources. No package was published and no",
  "personal credential was used.",
  "",
  "## Baseline",
  "",
  `- Pi: ${runtime.pi}`,
  `- Node: ${runtime.node}`,
  `- npm: ${runtime.npm}`,
  `- Platform: ${runtime.platform} ${runtime.arch}`,
  "",
  "## Commands",
  "",
  "```sh",
  "npm run fixtures:verify",
  "```",
  "",
  "## Checks",
  "",
];

for (const payload of payloads) {
  lines.push(`### ${payload.label}`, "");
  lines.push(`Generated: ${payload.generatedAt} — failures: ${payload.failures}`, "");
  lines.push("| Observation | Detail |", "| --- | --- |");
  for (const record of payload.records) {
    const detail = JSON.stringify(record.details).replace(/\|/g, "\\|");
    const short = detail.length > 400 ? `${detail.slice(0, 400)}…` : detail;
    lines.push(`| ${record.name} | ${short} |`);
  }
  lines.push("");
}

lines.push("## Not claimed by this evidence", "");
for (const item of NOT_CLAIMED) lines.push(`- ${item}`);
lines.push("");

writeFileSync(reportPath, lines.join("\n"));
console.log(`Report: ${reportPath}`);
console.log(
  `Checks: ${payloads.length}, failures: ${failures} (harness self-tests excluded)`
);
process.exitCode = failures > 0 ? 1 : 0;
